// Generates the Perpeto brand from code, then rasterizes it.
//
//   npm run brand:render
//
// The mark is a squared perpetual loop: two interlocking square rings, one per
// hedge leg, woven over-under at their two crossings and leaned 12 degrees
// upward (PRODUCT_SPEC section 12.1). It is drawn in one colour from the
// AgentFloor palette. The PERPETO wordmark is Space Grotesk Bold, outlined to
// paths with opentype.js, so no SVG depends on an installed font.
//
// Every SVG in assets/brand/perpeto-*.svg is an output of this script; edit
// the geometry here, never the SVG files. @resvg/resvg-js then renders the
// PNG paths that app.json references.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";
import opentype from "opentype.js";

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const brandDir = resolve(root, "assets", "brand");

/** The only colours the brand may use (AgentFloor tokens). */
export const PALETTE = { lime: "#CBFE42", paper: "#0F0F0F", ink: "#F1EFE6" };

// Mark geometry on a 1024 canvas, stroke centrelines. Ring B is ring A offset
// diagonally by OFFSET of a ring, a symmetric chain-link interlock whose
// bounding box is centred on (512, 512). The offset keeps both crossings well
// clear of the corners and leaves an open window where the rings overlap.
const STROKE = 72;
const GAP = 20; // clearance either side of the over-passing stroke
const RING = 330;
const OFFSET = 0.6;
const SPAN = RING * (1 + OFFSET);
const A = { x: 512 - SPAN / 2, y: 512 - SPAN / 2 };
const B = { x: A.x + RING * OFFSET, y: A.y + RING * OFFSET };
const LEAN = -12;

function ring({ x, y }) {
  return `M${x} ${y}H${x + RING}V${y + RING}H${x}Z`;
}

/**
 * The two weave cut-outs. Where ring A's right edge crosses ring B's top edge,
 * A passes over, so B is cut; where B's left edge crosses A's bottom edge, B
 * passes over, so A is cut. Each cut spans the crossing stroke plus GAP.
 */
function weaveMasks(id) {
  const half = STROKE / 2 + GAP;
  const cut = (cx, cy) =>
    `<rect x="${cx - half}" y="${cy - STROKE / 2 - 8}" width="${half * 2}" height="${STROKE + 16}" fill="#000"/>`;
  return `<mask id="${id}-a" maskUnits="userSpaceOnUse" x="0" y="0" width="1024" height="1024"><rect width="1024" height="1024" fill="#fff"/>${cut(B.x, A.y + RING)}</mask>` +
    `<mask id="${id}-b" maskUnits="userSpaceOnUse" x="0" y="0" width="1024" height="1024"><rect width="1024" height="1024" fill="#fff"/>${cut(A.x + RING, B.y)}</mask>`;
}

/** The mark as a group, in one colour, optionally scaled about the centre. */
export function markGroup(color, id, scale = 1) {
  const stroke = `fill="none" stroke="${color}" stroke-width="${STROKE}" stroke-linecap="square" stroke-linejoin="miter"`;
  return `<defs>${weaveMasks(id)}</defs>` +
    `<g transform="translate(512 512) scale(${scale}) rotate(${LEAN}) translate(-512 -512)">` +
    `<path d="${ring(A)}" ${stroke} mask="url(#${id}-a)"/>` +
    `<path d="${ring(B)}" ${stroke} mask="url(#${id}-b)"/>` +
    `</g>`;
}

const fontPath = require.resolve("@expo-google-fonts/space-grotesk/700Bold/SpaceGrotesk_700Bold.ttf");
const font = opentype.parse(readFileSync(fontPath).buffer.slice(0));

/**
 * PERPETO outlined to a single path, tracked at -0.03em, with its left edge at
 * x=0 and its baseline at y=0. Returns the path data and its advance width.
 */
export function wordmark(size) {
  const tracking = -0.03 * size;
  let x = 0;
  const parts = [];
  for (const glyph of font.stringToGlyphs("PERPETO")) {
    parts.push(glyph.getPath(x, 0, size).toPathData(2));
    x += (glyph.advanceWidth / font.unitsPerEm) * size + tracking;
  }
  return { d: parts.join(""), width: x - tracking };
}

const svg = (viewBox, body, comment) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">\n  <!-- ${comment} Generated by scripts/render-brand.mjs. -->\n  ${body}\n</svg>\n`;

/** Every brand source: file name → SVG text. */
export function sources() {
  const word = wordmark(132);
  const splashWidth = 1200;
  const splashHeight = 1200;
  return {
    "perpeto-icon.svg": svg(
      "0 0 1024 1024",
      `<rect width="1024" height="1024" fill="${PALETTE.lime}"/>${markGroup(PALETTE.paper, "icon", 0.82)}`,
      "App icon: paper mark on a lime tile; the OS masks the corners.",
    ),
    "perpeto-foreground.svg": svg(
      "0 0 1024 1024",
      markGroup(PALETTE.lime, "fg", 0.6),
      "Android adaptive foreground: lime mark inside the 66% safe zone over the #0F0F0F background.",
    ),
    "perpeto-monochrome.svg": svg(
      "0 0 1024 1024",
      markGroup(PALETTE.ink, "mono", 0.6),
      "Android themed icon: single-colour silhouette; the launcher recolours it.",
    ),
    "perpeto-mark-dark.svg": svg("0 0 1024 1024", markGroup(PALETTE.lime, "dark"), "Mark for dark surfaces."),
    "perpeto-mark-light.svg": svg("0 0 1024 1024", markGroup(PALETTE.paper, "light"), "Mark for light surfaces."),
    "perpeto-splash.svg": svg(
      `0 0 ${splashWidth} ${splashHeight}`,
      `<g transform="translate(${splashWidth / 2 - 512 * 0.5} 230) scale(0.5)">${markGroup(PALETTE.lime, "splash")}</g>` +
        `<path transform="translate(${(splashWidth - word.width) / 2} 900)" d="${word.d}" fill="${PALETTE.ink}"/>`,
      "Splash lockup: mark over the outlined wordmark; Expo composites it over #0F0F0F.",
    ),
  };
}

/** PNG outputs that app.json and the app reference. */
export const targets = [
  { source: "perpeto-icon.svg", output: "icon.png", width: 1024 },
  { source: "perpeto-foreground.svg", output: "android-foreground.png", width: 1024 },
  { source: "perpeto-monochrome.svg", output: "android-monochrome.png", width: 1024 },
  { source: "perpeto-splash.svg", output: "splash-lockup.png", width: 1200 },
  { source: "perpeto-mark-dark.svg", output: "mark-dark.png", width: 512 },
  { source: "perpeto-mark-light.svg", output: "mark-light.png", width: 512 },
  { source: "perpeto-icon.svg", output: "favicon.png", width: 196 },
];

function main() {
  for (const [name, text] of Object.entries(sources())) {
    writeFileSync(resolve(brandDir, name), text);
    console.warn(`wrote ${name}`);
  }
  for (const { source, output, width } of targets) {
    const text = readFileSync(resolve(brandDir, source), "utf8");
    const png = new Resvg(text, { fitTo: { mode: "width", value: width }, background: "rgba(0,0,0,0)" })
      .render()
      .asPng();
    writeFileSync(resolve(brandDir, output), png);
    console.warn(`rendered ${output} (${width}px) from ${source}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();

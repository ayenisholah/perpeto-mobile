/// <reference types="node" />
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

import { describe, expect, it } from "vitest";

/**
 * Guards the generated brand assets (scripts/render-brand.mjs): palette-only
 * colours, outlined text, square canvases, and every PNG that app.json and the
 * app reference present at its target size.
 */
const brandDir = resolve(__dirname, "..", "assets", "brand");
const PALETTE = new Set(["#CBFE42", "#0F0F0F", "#F1EFE6"]);
// Mask fills are luminance values inside <mask>, not brand colours.
const MASK_FILLS = new Set(["#000", "#FFF"]);

const sources = [
  "perpeto-icon.svg",
  "perpeto-foreground.svg",
  "perpeto-monochrome.svg",
  "perpeto-mark-dark.svg",
  "perpeto-mark-light.svg",
  "perpeto-splash.svg",
];

const pngs: readonly [string, number][] = [
  ["icon.png", 1024],
  ["android-foreground.png", 1024],
  ["android-monochrome.png", 1024],
  ["splash-lockup.png", 1200],
  ["mark-dark.png", 512],
  ["mark-light.png", 512],
  ["favicon.png", 196],
];

function pngSize(file: string): { width: number; height: number } {
  const header = readFileSync(resolve(brandDir, file)).subarray(0, 24);
  expect(header.subarray(1, 4).toString("ascii")).toBe("PNG");
  return { width: header.readUInt32BE(16), height: header.readUInt32BE(20) };
}

describe.each(sources)("%s", (file) => {
  const svg = readFileSync(resolve(brandDir, file), "utf8");

  it("is generated, not hand-edited", () => {
    expect(svg).toContain("Generated by scripts/render-brand.mjs");
  });

  it("uses only AgentFloor palette colours", () => {
    const colours = [...svg.matchAll(/#[0-9A-Fa-f]{3,6}\b/gu)].map(([hex]) => hex.toUpperCase());
    expect(colours.length).toBeGreaterThan(0);
    for (const colour of colours) {
      expect(PALETTE.has(colour) || MASK_FILLS.has(colour), colour).toBe(true);
    }
  });

  it("carries no live text, so it renders without installed fonts", () => {
    expect(svg).not.toMatch(/<text\b/u);
  });

  it("has a square canvas", () => {
    const [, , , width, height] = /viewBox="(\d+) (\d+) (\d+) (\d+)"/u.exec(svg) ?? [];
    expect(width).toBeDefined();
    expect(width).toBe(height);
  });

  it("uses square stroke ends to match the radius-0 system", () => {
    expect(svg).not.toContain('stroke-linecap="round"');
  });
});

describe("rendered PNGs", () => {
  it.each(pngs)("%s exists at %ipx square", (file, size) => {
    expect(existsSync(resolve(brandDir, file))).toBe(true);
    expect(pngSize(file)).toEqual({ width: size, height: size });
  });
});
